CREATE TABLE IF NOT EXISTS denominacoes (
 id BIGSERIAL PRIMARY KEY,
 nome VARCHAR(160) NOT NULL,
 telefone VARCHAR(30), cidade VARCHAR(100), estado VARCHAR(2),
 ativo BOOLEAN NOT NULL DEFAULT TRUE, criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS usuarios (
 id BIGSERIAL PRIMARY KEY,
 denominacao_id BIGINT NOT NULL REFERENCES denominacoes(id) ON DELETE CASCADE,
 nome VARCHAR(160) NOT NULL, email VARCHAR(180) NOT NULL,
 telefone VARCHAR(30), senha_hash TEXT NOT NULL,
 perfil VARCHAR(40) NOT NULL DEFAULT 'ADMIN', ativo BOOLEAN NOT NULL DEFAULT TRUE,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(denominacao_id,email)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_usuario_email_global ON usuarios(LOWER(email));
CREATE TABLE IF NOT EXISTS congregacoes (
 id BIGSERIAL PRIMARY KEY,
 denominacao_id BIGINT NOT NULL REFERENCES denominacoes(id) ON DELETE CASCADE,
 nome VARCHAR(160) NOT NULL, cidade VARCHAR(100), estado VARCHAR(2), endereco TEXT,
 ativo BOOLEAN NOT NULL DEFAULT TRUE, criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
